"""Copy the numbers the web page quotes out of results/ into web/data.js.

The page never invents a benchmark or study number: everything in the race and
nested sections comes from this file, which comes from the saved JSON results.
data.js is a plain script (window.SF_DATA = {...}) so the page also works when
opened straight from disk, where fetch() of local files is blocked.

Usage: python scripts/export_web_data.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def main() -> int:
    bench = json.loads((RES / "bench" / "bench.json").read_text())
    scen = "base 10y (120 steps)"
    rows = [r for r in bench["rows"] if r["scenario"] == scen and "median_ms" in r]

    def pick(engine, n=None):
        rs = [r for r in rows if r["engine"] == engine and (n is None or r["n_paths"] == n)]
        return max(rs, key=lambda r: r["n_paths"]) if rs else None

    n_race = 1 << 22
    tri, th = pick("triton_fused_fp32", n_race), pick("torch_randn_fp32", n_race)
    tc = pick("torch_compile_graph_fp32", n_race)
    # NumPy: the row with the best throughput (as in segfund bench's "x NumPy" column), extrapolated
    # to the race size by path-steps/s (its cost is linear in paths)
    npy = max((r for r in rows if r["engine"] == "numpy_fp64"), key=lambda r: r["path_steps_per_s"])
    steps = tri["n_steps"]
    race = dict(
        n_paths=n_race, n_steps=steps,
        lanes=[
            dict(key="triton", label="Fused Triton kernel", note="one GPU launch, fp32",
                 ms=tri["median_ms"], quotable=tri["quotable"], measured=True),
            *([dict(key="compile", label="PyTorch, compiled", note="torch.compile + CUDA graph, GPU",
                    ms=tc["median_ms"], quotable=tc["quotable"], measured=True)] if tc else []),
            dict(key="torch", label="Plain PyTorch", note="unfused, torch.randn, GPU",
                 ms=th["median_ms"], quotable=th["quotable"], measured=True),
            dict(key="numpy", label="NumPy reference", note=f"one CPU core, fp64; extrapolated from {npy['n_paths']:,} paths",
                 ms=n_race * steps / npy["path_steps_per_s"] * 1e3, quotable=False, measured=False),
        ],
        gpu=bench["gpu"].get("name"), cpu="Intel Core i7-14700HX",
        timestamp=bench["meta"]["timestamp"], commit=bench["meta"]["git_commit"],
    )
    nst = json.loads((RES / "nested" / "nested_study.json").read_text())["summary"]
    gt = nst["gt"]
    nested = dict(
        inner_paths=gt["paths"], gpu_s=gt["wall_s"], cpu_s_est=gt["paths"] * nst["cpu_s_per_inner_path"],
        cte95=gt["cte95"]["cte"], cte95_se=gt["cte95"]["se"], n_outer=gt["cte95"]["n"],
    )
    v1 = json.loads((RES / "validation" / "phase1_cpu.json").read_text())
    v2 = json.loads((RES / "validation" / "phase2_gpu.json").read_text())
    count = lambda d: [sum(c["passed"] for c in d["checks"] if c.get("gated", True)),  # noqa: E731
                       sum(1 for c in d["checks"] if c.get("gated", True))]
    run = json.loads((RES / "runs" / "base_gpu_4M.json").read_text())
    data = dict(
        race=race, nested=nested,
        validation=dict(cpu=count(v1), gpu=count(v2)),
        reference=dict(n_paths=run["n_paths"], pv=run["pv"]["mean"], pv_se=run["pv"]["se"],
                       cte95=run["cte"]["cte95"]["cte"], cte95_se=run["cte"]["cte95"]["se"]),
    )
    out = ROOT / "web" / "data.js"
    out.write_text("/* generated by scripts/export_web_data.py from results/; do not edit */\n"
                   f"window.SF_DATA = {json.dumps(data, indent=1)};\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
